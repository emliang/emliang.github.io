// Re-render the article's data-tex elements after editing their LaTeX source.
// Requires KaTeX 0.16.22 (set KATEX_MODULE to its package path if needed).
const fs = require('node:fs');
const path = require('node:path');
const katex = require(process.env.KATEX_MODULE || 'katex');
if (katex.version !== '0.16.22') throw new Error('Use KaTeX 0.16.22 to preserve the checked rendering');
const articles = process.argv.slice(2).length ? process.argv.slice(2) : [
  'blog/homeomorphism-methods/index.html', 'blog/hard-constrained-machine-learning/index.html'
];
const unescape = value => value.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
for (const file of articles) {
const article = path.resolve(__dirname, '..', file);
let count = 0;
const source = fs.readFileSync(article, 'utf8').replace(/<!-- math:start -->(<(span|div)\b[^>]*\bdata-tex="([^"]*)"[^>]*>)[\s\S]*?<\/\2><!-- math:end -->/g, (_, opening, tag, tex) => {
  const rendered = katex.renderToString(unescape(tex), {
    displayMode: tag === 'div', output: 'htmlAndMathml', throwOnError: true, strict: 'error', trust: false
  });
  count++;
  return `<!-- math:start -->${opening}${rendered}</${tag}><!-- math:end -->`;
});
if (!count) throw new Error('No marked formulas found');
fs.writeFileSync(article, source);
console.log(`Rendered ${count} formulas in ${file} with KaTeX ${katex.version}`);
}

